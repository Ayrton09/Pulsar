using System.Security.Cryptography;
using System.Text.Json;
using Microsoft.Extensions.Logging;
using Microsoft.Extensions.Logging.Abstractions;
using Pulsar.Agent.Core.Processes;
using Pulsar.Agent.Core.Security;
using Pulsar.Contracts;

namespace Pulsar.Agent.Core.Servers;

/// <summary>What the agent keeps about a server between runs (<c>state\servers\{id}.json</c>).</summary>
/// <param name="DesiredRunning">Whether it should be running (the panel's intent, or the game's own stop).</param>
/// <param name="ResumeOnStart">It was running when the agent stopped in an orderly way: started again next time.</param>
/// <param name="RconPassword">Generated by the agent for games with an RCON console (docs/architecture/04, "Console").</param>
public sealed record ServerRecord(Guid ServerId, ServerRuntimeSpec Spec, bool DesiredRunning, bool ResumeOnStart, string? RconPassword = null)
{
    public override string ToString() => $"ServerRecord {{ ServerId = {ServerId} }}";
}

/// <summary>
/// The host process a server's game runs in (docs/architecture/06, "Server hosts") and how far the agent read its
/// console: its output offset in the host, and its position in the game's log file (<c>logfile+rcon</c>).
/// </summary>
/// <param name="Ready">The game had passed its readiness check.</param>
/// <param name="Stopping">The game was being stopped.</param>
public sealed record GameHostRecord(Guid ServerId, GameHostReference Host, long ConsoleOffset, long LogPosition, bool Ready, bool Stopping = false);

/// <summary>A game a backup asked to stop saving, and the commands that make it save again (the manifest's <c>backup.save.resume</c>).</summary>
public sealed record PausedSave(Guid ServerId, IReadOnlyList<string> Resume);

/// <summary>
/// Server records and undelivered operation results, as JSON files in the agent's state directory (SYSTEM and
/// Administrators only). Every write replaces the file atomically. Records hold secrets (secret variables, the RCON
/// password), so they are stored encrypted (<see cref="IStateProtector"/>, DPAPI on Windows) inside a small envelope
/// that names the protection; a record written before that (plain JSON) is still read. A file that cannot be read
/// (corrupt, or protected on another machine) is set aside as <c>*.json.unreadable</c> and logged: it must not keep the
/// other servers from loading, nor the agent from connecting. One that cannot be opened (another program holds it) is
/// skipped and logged, and stays for the next time.
/// </summary>
public sealed partial class ServerStore(AgentPaths paths, IStateProtector protector, ILogger<ServerStore>? logger = null)
{
    private static readonly JsonSerializerOptions s_options = new(ProtocolJson.Options) { WriteIndented = true };

    // A temporary file older than this belongs to a write that never finished (see DeleteOrphans).
    private static readonly TimeSpan s_orphanAge = TimeSpan.FromMinutes(5);

    private readonly ILogger _logger = logger ?? (ILogger)NullLogger.Instance;

    public IReadOnlyList<ServerRecord> LoadAll()
    {
        if (!Directory.Exists(paths.ServersStateDirectory))
        {
            return [];
        }

        DeleteOrphans(paths.ServersStateDirectory);
        return [.. Directory.EnumerateFiles(paths.ServersStateDirectory, "*.json").Select(f => ReadOrSetAside(f, ReadRecord, serverRecord: true))
            .OfType<ServerRecord>()];
    }

    /// <summary>
    /// The record of <paramref name="serverId"/> set aside as unreadable, if there is one: the server's directory and
    /// account are still on the node, but their names (from its short id) are inside the record.
    /// </summary>
    public string? SetAsideRecord(Guid serverId)
    {
        var file = Path.Combine(paths.ServersStateDirectory, $"{serverId:N}.json.unreadable");
        return File.Exists(file) ? file : null;
    }

    /// <summary>Whether the node has a record of <paramref name="serverId"/>, readable or set aside.</summary>
    public bool Exists(Guid serverId)
    {
        var file = Path.Combine(paths.ServersStateDirectory, $"{serverId:N}.json");
        return File.Exists(file) || File.Exists(file + ".unreadable");
    }

    public ServerRecord? Load(Guid serverId)
    {
        var file = Path.Combine(paths.ServersStateDirectory, $"{serverId:N}.json");
        return File.Exists(file) ? ReadRecord(file) : null;
    }

    public void Save(ServerRecord record)
    {
        ArgumentNullException.ThrowIfNull(record);
        var data = protector.Protect(JsonSerializer.SerializeToUtf8Bytes(record, s_options));
        Write(paths.ServersStateDirectory, record.ServerId, new ProtectedRecord(protector.Name, data));
    }

    public void Delete(Guid serverId) => File.Delete(Path.Combine(paths.ServersStateDirectory, $"{serverId:N}.json"));

    public IReadOnlyList<GameHostRecord> LoadHosts()
    {
        if (!Directory.Exists(paths.HostsStateDirectory))
        {
            return [];
        }

        DeleteOrphans(paths.HostsStateDirectory);
        return [.. Directory.EnumerateFiles(paths.HostsStateDirectory, "*.json").Select(f => ReadOrSetAside(f, Read<GameHostRecord>))
            .OfType<GameHostRecord>()];
    }

    public void SaveHost(GameHostRecord record)
    {
        ArgumentNullException.ThrowIfNull(record);
        Write(paths.HostsStateDirectory, record.ServerId, record);
    }

    public void DeleteHost(Guid serverId) => File.Delete(Path.Combine(paths.HostsStateDirectory, $"{serverId:N}.json"));

    public IReadOnlyList<PausedSave> LoadPausedSaves()
    {
        if (!Directory.Exists(paths.PausedSavesDirectory))
        {
            return [];
        }

        DeleteOrphans(paths.PausedSavesDirectory);
        return [.. Directory.EnumerateFiles(paths.PausedSavesDirectory, "*.json").Select(f => ReadOrSetAside(f, Read<PausedSave>))
            .OfType<PausedSave>()];
    }

    public void SavePausedSave(PausedSave paused)
    {
        ArgumentNullException.ThrowIfNull(paused);
        Write(paths.PausedSavesDirectory, paused.ServerId, paused);
    }

    public void DeletePausedSave(Guid serverId) => File.Delete(Path.Combine(paths.PausedSavesDirectory, $"{serverId:N}.json"));

    public IReadOnlyList<OperationCompleted> PendingResults()
    {
        if (!Directory.Exists(paths.OutboxDirectory))
        {
            return [];
        }

        DeleteOrphans(paths.OutboxDirectory);
        return [.. Directory.EnumerateFiles(paths.OutboxDirectory, "*.json").Select(f => ReadOrSetAside(f, Read<OperationCompleted>))
            .OfType<OperationCompleted>()];
    }

    public void SaveResult(OperationCompleted result)
    {
        ArgumentNullException.ThrowIfNull(result);
        Write(paths.OutboxDirectory, result.OperationId, result);
    }

    public void DeleteResult(Guid operationId) => File.Delete(Path.Combine(paths.OutboxDirectory, $"{operationId:N}.json"));

    private T? ReadOrSetAside<T>(string file, Func<string, T?> read, bool serverRecord = false) where T : class
    {
        try
        {
            return read(file);
        }
        catch (Exception ex) when (ex is FileNotFoundException or DirectoryNotFoundException)
        {
            // Deleted between the listing and the read (a result delivered, a host forgotten): there is nothing to load.
            return null;
        }
        catch (Exception ex) when (ex is IOException or UnauthorizedAccessException)
        {
            // Held by another program (a scanner) past the retries: skipped this time, not set aside, since it may be fine.
            LogNotRead(Path.GetFileName(file), ex.Message);
            return null;
        }
        catch (Exception ex) when (ex is JsonException or InvalidDataException or CryptographicException or NotSupportedException)
        {
            LogUnreadable(Path.GetFileName(file), ex.Message);
            if (serverRecord && Guid.TryParseExact(Path.GetFileNameWithoutExtension(file), "N", out var serverId))
            {
                // The name is all that can be read: say which server is left behind, for whoever cleans up.
                LogServerSetAside(serverId);
            }

            try
            {
                File.Move(file, file + ".unreadable", overwrite: true);
            }
            catch (Exception moveFailed) when (moveFailed is IOException or UnauthorizedAccessException)
            {
                LogNotSetAside(Path.GetFileName(file), moveFailed.Message);
            }

            return null;
        }
    }

    /// <summary>
    /// Deletes the temporary files of writes that never finished (the agent stopped between creating one and moving it
    /// over its record). Only ones a few minutes old: a write in progress is never touched. One that cannot be deleted
    /// now is tried again at the next load.
    /// </summary>
    private void DeleteOrphans(string directory)
    {
        foreach (var temporary in Directory.EnumerateFiles(directory, "*.tmp"))
        {
            try
            {
                if (temporary.EndsWith(".tmp", StringComparison.OrdinalIgnoreCase) && DateTime.UtcNow - File.GetLastWriteTimeUtc(temporary) > s_orphanAge)
                {
                    File.Delete(temporary);
                    LogOrphanDeleted(temporary);
                }
            }
            catch (Exception ex) when (ex is IOException or UnauthorizedAccessException)
            {
                // Held by another program: next time.
            }
        }
    }

    private ServerRecord? ReadRecord(string file)
    {
        byte[] content;
        using (var stream = OpenShared(file))
        {
            content = new byte[stream.Length];
            stream.ReadExactly(content);
        }

        using var document = JsonDocument.Parse(content);
        if (document.RootElement.ValueKind != JsonValueKind.Object)
        {
            throw new JsonException($"{Path.GetFileName(file)} is not a JSON object.");
        }

        if (!document.RootElement.TryGetProperty("protection", out _))
        {
            return document.RootElement.Deserialize<ServerRecord>(s_options); // written before records were encrypted
        }

        var envelope = document.RootElement.Deserialize<ProtectedRecord>(s_options)!;
        if (envelope.Protection != protector.Name)
        {
            throw new InvalidDataException($"{Path.GetFileName(file)} is protected with '{envelope.Protection}', not '{protector.Name}'.");
        }

        return JsonSerializer.Deserialize<ServerRecord>(protector.Unprotect(envelope.Data), s_options);
    }

    private sealed record ProtectedRecord(string Protection, byte[] Data);

    private static T? Read<T>(string file)
    {
        using var stream = OpenShared(file);
        return JsonSerializer.Deserialize<T>(stream, s_options);
    }

    // Writes replace a file while it may be read (an operation's result saved while results are delivered). The reader
    // shares everything, and each side retries for a moment: Windows refuses to replace a file another handle has open,
    // and to open one that is being replaced.
    private static FileStream OpenShared(string file) =>
        Transient(() => new FileStream(file, FileMode.Open, FileAccess.Read, FileShare.ReadWrite | FileShare.Delete));

    private static T Transient<T>(Func<T> action)
    {
        for (var attempt = 1; ; attempt++)
        {
            try
            {
                return action();
            }
            catch (Exception ex) when (attempt < 20 && ex is UnauthorizedAccessException or IOException
                && ex is not (FileNotFoundException or DirectoryNotFoundException))
            {
                Thread.Sleep(10 * attempt);
            }
        }
    }

    /// <summary>
    /// Written to a file of its own (two writers of one record never share it), on the disk before it replaces the
    /// record: a power loss right after the replacement must not leave an empty record.
    /// </summary>
    private static void Write<T>(string directory, Guid id, T value)
    {
        Directory.CreateDirectory(directory);
        var file = Path.Combine(directory, $"{id:N}.json");
        var temporary = Path.Combine(directory, $"{id:N}.{Guid.NewGuid():N}.tmp");
        try
        {
            using (var stream = new FileStream(temporary, FileMode.CreateNew, FileAccess.Write, FileShare.None, 4096, FileOptions.WriteThrough))
            {
                stream.Write(JsonSerializer.SerializeToUtf8Bytes(value, s_options));
                stream.Flush(flushToDisk: true);
            }

            Transient(() =>
            {
                File.Move(temporary, file, overwrite: true);
                return true;
            });
        }
        finally
        {
            File.Delete(temporary); // nothing left when it was moved
        }
    }

    [LoggerMessage(Level = LogLevel.Error, Message = "State file {File} cannot be read and is set aside (.unreadable): {Reason}")]
    private partial void LogUnreadable(string file, string reason);

    [LoggerMessage(Level = LogLevel.Error,
        Message = "Server {ServerId} is not loaded: its record cannot be read, so its directory and account stay on the node until removed by hand")]
    private partial void LogServerSetAside(Guid serverId);

    [LoggerMessage(Level = LogLevel.Error, Message = "State file {File} could not be set aside: {Reason}")]
    private partial void LogNotSetAside(string file, string reason);

    [LoggerMessage(Level = LogLevel.Error, Message = "State file {File} cannot be opened now (skipped this time): {Reason}")]
    private partial void LogNotRead(string file, string reason);

    [LoggerMessage(Level = LogLevel.Information, Message = "Deleted {File}, the temporary file of a state write that never finished")]
    private partial void LogOrphanDeleted(string file);
}
